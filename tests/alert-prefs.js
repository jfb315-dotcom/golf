const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const fs = require('fs');
const stub = fs.readFileSync(__dirname + '/stub.js', 'utf8');
const html = fs.readFileSync(__dirname + '/../index.html', 'utf8');
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const page = await ctx.newPage();
  page.on('pageerror', e => { console.log('PAGE ERROR', e.message); fails++; });
  page.on('dialog', d => d.accept());
  await ctx.route('**/*', r => { const u = r.request().url();
    if (u.includes('gstatic')) return r.fulfill({ contentType: 'text/javascript', body: u.includes('app-compat') ? stub : '' });
    if (u.startsWith('http://app.test/')) return r.fulfill({ contentType: 'text/html', body: html });
    return r.abort(); });
  await page.addInitScript(() => { window.__docsInit = {}; });
  await page.goto('http://app.test/'); await page.waitForTimeout(400); await page.evaluate(() => { if (document.getElementById('step-home')?.classList.contains('active')) showScreen('step-1'); });
  const count = () => page.innerText('#alerts-count');
  ok(await count() === '13 of 13 on', 'first time: all on');
  await page.click('#alerts-row');
  await page.click('.alerts-all button:text-is("All off")');
  ok(await count() === '0 of 13 on', 'All off turns every switch off');
  await page.click('.alerts-all button:text-is("All on")');
  ok(await count() === '13 of 13 on', 'All on turns them back on');
  await page.click('.alerts-all button:text-is("All off")');
  for (const t of ['birdies', 'skins', 'final']) await page.check('#alert-' + t);
  ok(await count() === '3 of 13 on', 'pick just three: ' + await count());
  await page.screenshot({ path: __dirname + '/shots/alerts-all.png', clip: { x: 0, y: (await page.evaluate(() => document.getElementById('alerts-setup').getBoundingClientRect().top)) - 10, width: 390, height: 420 } });
  await page.click('#step-alerts .back-link-top');
  // start a round with these, then finalize: next round starts with the same three
  await page.evaluate(() => { document.getElementById('group-count').value = 2; document.getElementById('players-per-group').value = 2; });
  await page.click('#step-1 .bar-primary[onclick="goToStep2()"]');
  for (const [id, n] of [['g1-p1','Brent'],['g1-p2','John'],['g2-p1','Jordia'],['g2-p2','Mike']]) await page.fill(`#${id}-name`, n);
  await page.evaluate(() => saveRosterCache());
  await page.click('#btn-step2-next'); await page.waitForTimeout(400);
  const saved = await page.evaluate(() => window.__doc.roundData.alerts);
  ok(saved.birdies && saved.skins && saved.final && !saved.doubles && !saved.behind, 'round uses the three picked');
  await page.evaluate(() => { for (let h = 1; h <= 18; h++) [[1,1],[1,2],[2,1],[2,2]].forEach(([g,p]) => { scoresDb[g][p][h] = 4; }); });
  await page.click('#step-3 button:has-text("Finalize / Archive Round")');
  for (const d of '1234') await page.click(`.pin-pad button:text-is("${d}")`);
  await page.waitForTimeout(500);
  await page.evaluate(() => closeShareModal());
  ok(await count() === '3 of 13 on', 'after finalizing, the next round starts with the same three');
  // and after closing and reopening the app
  const p2 = await ctx.newPage(); await p2.addInitScript(() => { window.__docsInit = {}; });
  await p2.goto('http://app.test/'); await p2.waitForTimeout(400); await p2.evaluate(() => { if (document.getElementById('step-home')?.classList.contains('active')) showScreen('step-1'); });
  ok(await p2.innerText('#alerts-count') === '3 of 13 on' && await p2.isChecked('#alert-skins') && !(await p2.isChecked('#alert-doubles')), 'reopening the app keeps them too');
  await browser.close();
  console.log(fails ? `${fails} FAILED` : 'ALL PASS'); process.exit(fails ? 1 : 0);
})();
