const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const fs = require('fs');
const stub = fs.readFileSync(__dirname + '/stub.js', 'utf8');
const html = fs.readFileSync(__dirname + '/../index.html', 'utf8');
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  page.on('pageerror', e => { console.log('PAGE ERROR', e.message); fails++; });
  await page.route('**/*', r => { const u = r.request().url();
    if (u.includes('gstatic')) return r.fulfill({ contentType: 'text/javascript', body: u.includes('app-compat') ? stub : '' });
    if (u.startsWith('http://app.test/')) return r.fulfill({ contentType: 'text/html', body: html });
    return r.abort(); });
  await page.goto('http://app.test/'); await page.waitForTimeout(500);
  await page.click('.home-tile:has-text("How it works")'); await page.waitForTimeout(200);
  ok(await page.isVisible('#step-help') && (await page.$$('.help')).length === 11, 'How it works page with 11 sections');
  await page.screenshot({ path: __dirname + '/shots/help.png' });
  await page.click('.help:nth-of-type(2) summary'); await page.waitForTimeout(100);
  ok(await page.evaluate(() => { let d = document.querySelectorAll('#step-help details')[1]; return d.open && d.innerText.includes('balanced by handicap'); }), 'sections open');
  await page.click('#step-help .back-link-top');
  await page.evaluate(() => openSignupModal()); await page.waitForTimeout(200);
  await page.screenshot({ path: __dirname + '/shots/ask-modal.png' });
  await page.click('#signup-modal .btn-primary'); await page.waitForTimeout(300);
  ok((await page.inputValue('#text-body')).startsWith('⛳ Golf '), 'default message Golf <day>?');
  await page.screenshot({ path: __dirname + '/shots/send-modal.png' });
  await page.evaluate(() => document.getElementById('text-modal').classList.remove('active'));
  ok(await page.evaluate(() => alertsCartTag()) === 'admin', "organizer's phone is tagged for its own alerts");
  await page.evaluate(() => openAlertView('whos')); await page.waitForTimeout(300);
  ok(await page.isVisible('#step-whos'), "tapping a sign-up alert opens Who's playing");
  await page.evaluate(() => openAlertsScreen('step-home'));
  ok(await page.isVisible('#alert-signups') && await page.isChecked('#alert-signups'), 'Alerts page has "Sign-up answers" (on)');
  await page.uncheck('#alert-signups');
  ok(await page.evaluate(() => window.__docs.signup.notify === false), 'turning it off is saved on the sign-up');
  await page.screenshot({ path: __dirname + '/shots/alerts-signups.png', fullPage: true });
  await browser.close();
  console.log(fails ? `${fails} FAILED` : 'ALL PASS'); process.exit(fails ? 1 : 0);
})();
