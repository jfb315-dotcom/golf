  ok(await page.getAttribute('.segmented[data-select="hole-format"] button[data-value="18"]', 'aria-pressed') === 'true', '18 holes selected by default');
  await page.click('text=9 holes');
  ok(await page.inputValue('#hole-format') === '9' && await page.isVisible('#nine-hole-match-type-container'), '9 holes toggle sets format and shows 9-hole match');
  ok(await page.innerText('#live-buyin-display') === 'ENTRY FEE\n$130', 'nassau 9 still 3 bets');
  await page.click('text=Straight 9 (1 bet)');
  ok(await page.inputValue('#nine-hole-type') === 'straight' && (await page.innerText('#live-buyin-display')).includes('$50'), 'straight 9 recalculates fee to $50');
  await page.click('text=18 holes');
  ok(!(await page.isVisible('#nine-hole-match-type-container')), 'back to 18 hides 9-hole match');
  await page.click('text=Start on 10');
  ok(await page.inputValue('#start-type') === 'back', 'start on 10 toggle');
  await page.click('[aria-label="More players"]');
  ok(await page.inputValue('#players-per-group') === '4', 'players capped at 4');
  await page.click('[aria-label="Fewer players"]'); await page.click('[aria-label="Fewer players"]');
  ok(await page.inputValue('#players-per-group') === '2', 'minus lowers players');
  await page.click('[aria-label="More teams"]');
  ok(await page.inputValue('#group-count') === '3', 'plus raises teams');
  await page.click('label:has(#fmt-1-birdies)');
  ok(await page.isChecked('#fmt-1-birdies'), 'birdie switch toggles');
  await page.click('#step-1 .bar-primary[onclick="goToStep2()"]'); await page.waitForTimeout(200);
  ok(await page.isVisible('#step-2'), 'Next goes to rosters');
  await page.fill('#g1-p1-name', 'Eddie'); await page.dispatchEvent('#g1-p1-name', 'change');
  await page.fill('#g1-p2-name', 'Bo'); await page.fill('#g2-p1-name', 'Cy'); await page.fill('#g2-p2-name', 'Di');
  await page.fill('#g3-p1-name', 'Al'); await page.fill('#g3-p2-name', 'Ty');
