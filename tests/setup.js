  ok(dateBox, 'date chip inside the screen');
  await page.click('text=Scramble carts');
  ok(await page.innerText('#btn-step2-next') === 'Next: Set carts' && !(await page.isVisible('#btn-step2-text')) && !(await page.isVisible('#g1-time-wrap')), 'scramble toggle switches button and hides tee times');
  await page.click('text=Ride with team');
  ok(await page.innerText('#btn-step2-next') === 'Start round' && await page.isVisible('#btn-step2-text') && await page.isVisible('#g1-time-wrap'), 'ride with team restores');
  await page.click('text=‹ Setup');
  ok(await page.isVisible('#step-1') && await page.inputValue('#group-count') === '3', 'back to setup keeps values');
  await page.click('#step-1 .bar-primary[onclick="goToStep2()"]');
  ok(await page.inputValue('#g1-p1-name') === 'Eddie' && await page.inputValue('#g1-p1-strokes') === '7', 'roster remembered, saved strokes filled');
  page.on('dialog', d => d.accept());
  await page.click('#btn-step2-next'); await page.waitForTimeout(300);
  ok(await page.isVisible('#step-3') && await page.evaluate(() => roundData.startType === 'back' && roundData.groups.length === 3 && roundData.formats.join() === '2,3' && roundData.birdieRules[2] === true), 'round starts with chosen settings');
