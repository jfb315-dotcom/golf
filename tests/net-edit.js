const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const fs = require('fs');
const stub = fs.readFileSync(__dirname + '/stub.js', 'utf8');
const html = fs.readFileSync(__dirname + '/../index.html', 'utf8');
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  page.setDefaultTimeout(5000);
  page.on('pageerror', e => { console.log('PAGE ERROR', e.message); fails++; });
  page.on('dialog', d => d.accept());
  await page.route('**/*', r => { const u = r.request().url();
    if (u.includes('gstatic')) return r.fulfill({ contentType: 'text/javascript', body: u.includes('app-compat') ? stub : '' });
    if (u.startsWith('http://app.test/')) return r.fulfill({ contentType: 'text/html', body: html });
    return r.abort(); });
  await page.addInitScript(() => { window.__docsInit = {}; });
  await page.goto('http://app.test/'); await page.waitForTimeout(300);
  await page.evaluate(() => { if (document.getElementById('step-home')?.classList.contains('active')) showScreen('step-1'); });
  await page.evaluate(() => { document.getElementById('group-count').value = 2; document.getElementById('players-per-group').value = 2; });
  await page.evaluate(() => startNewRound('om'));
  ok(await page.isVisible('#om-nassau-net') && !(await page.isChecked('#om-nassau-net')), 'setup shows "Strokes count on the Nassau", off by default');
  await page.click('#step-1 .bar-primary[onclick="goToStep2()"]');
  for (const [id, n] of [['g1-p1','Brent'],['g1-p2','John'],['g2-p1','Jordia'],['g2-p2','Mike']]) await page.fill(`#${id}-name`, n);
  await page.evaluate(() => saveRosterCache());
  await page.click('#btn-step2-next'); await page.waitForTimeout(300);
  await page.evaluate(() => { [[1,1,4],[1,2,5],[2,1,5],[2,2,5]].forEach(([g,p,v]) => { scoresDb[g][p][1] = v; }); saveScoresToCloud([[1,1],[1,2],[2,1],[2,2]], 1); });
  ok(await page.evaluate(() => roundData.ourMatch.nassauNet === false), 'round starts with a gross Nassau');
  ok(await page.evaluate(() => /^NassauNostrokes/.test(document.createRange().createContextualFragment(ourMatchRulesHTML(roundData)).querySelector('.om-rule').textContent.replace(/\s+/g, ''))), 'rules: gross Nassau says No strokes');
  // mid-round: turn it on from Edit setup
  await page.click('text=Edit setup / rosters'); await page.waitForTimeout(150);
  await page.evaluate(() => document.getElementById('om-nassau-net').scrollIntoView({ block: 'center' }));
  await page.screenshot({ path: __dirname + '/shots/nassau-net-setup.png' });
  await page.check('#om-nassau-net');
  await page.click('#step-1 .bar-primary[onclick="goToStep2()"]'); await page.waitForTimeout(150);
  await page.click('#btn-step2-next'); await page.waitForTimeout(300);
  ok(await page.evaluate(() => roundData.ourMatch.nassauNet === true && window.__docs.active_round.roundData.ourMatch.nassauNet === true), 'turned on mid-round, saved to the round');
  ok(await page.evaluate(() => scoresDb[1][1][1] === 4 && scoresDb[2][1][1] === 5), 'scores kept');
  await page.click('text=View standings'); await page.waitForTimeout(200);
  const nassauView = await page.evaluate(() => { showOmTab('nassau'); return document.querySelector('.om-tab-pane[data-tab="nassau"]').textContent.replace(/\s+/g, ' '); });
  ok(/Low ball net \(strokes count\)/.test(nassauView) && /Nassau net/.test(await page.innerText('#our-match .om-grid-rules')), 'strokes count on the Nassau: the Nassau view and the money table say net');
  ok(!(await page.$('details[data-fold="live-rules"]')) || !(await page.isVisible('details[data-fold="live-rules"]')), 'no rules dropdown on an Our Match round (it is in How it works)');
  await page.evaluate(() => { showOmTab('nassau'); switchScreen('step-dashboard', 'step-3'); });
  await page.click('text=Edit setup / rosters'); await page.waitForTimeout(150);
  ok(await page.isChecked('#om-nassau-net'), 'editing again shows it on');
  await page.click('text=Cancel edit'); await page.waitForTimeout(150);
  await browser.close();
  console.log(fails ? `${fails} FAILED` : 'ALL PASS'); process.exit(fails ? 1 : 0);
})();
