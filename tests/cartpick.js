const { chromium, devices } = require('/opt/node22/lib/node_modules/playwright');
const fs = require('fs');
const stub = fs.readFileSync(__dirname + '/stub.js', 'utf8');
const html = fs.readFileSync(__dirname + '/../index.html', 'utf8');
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const route = p => p.route('**/*', r => { const u = r.request().url();
    if (u.includes('gstatic')) return r.fulfill({ contentType: 'text/javascript', body: u.includes('app-compat') ? stub : '' });
    if (u.startsWith('http://app.test/')) return r.fulfill({ contentType: 'text/html', body: html });
    return r.abort(); });
  const admin = await browser.newPage({ viewport: { width: 390, height: 844 } });
  admin.on('dialog', d => d.accept());
  await route(admin);
  await admin.goto('http://app.test/'); await admin.waitForTimeout(500);
  await admin.evaluate(() => showScreen('step-1'));
  await admin.evaluate(() => { document.getElementById('group-count').value = 2; document.getElementById('players-per-group').value = 2; });
  await admin.click('text=Next: Rosters');
  for (const [id, n] of [['#g1-p1-name','Brent'],['#g1-p2-name','Mike'],['#g2-p1-name','John'],['#g2-p2-name','Chad']]) await admin.fill(id, n);
  await admin.evaluate(() => saveRosterCache());
  await admin.click('#btn-step2-next'); await admin.waitForTimeout(500);
  await admin.evaluate(() => openShareMenu());
  const msg = await admin.evaluate(() => cartShareMessages[1]);
  const link = msg.match(/http\S+/)[0];
  const rid = await admin.evaluate(() => String(roundData.roundId));
  ok(link.endsWith(`cart.html?cart=2&r=${rid}`), 'cart links carry the round: ' + link);
  const docs = await admin.evaluate(() => window.__docs);
  const iphone = { ...devices['iPhone 13'], deviceScaleFactor: 2 };
  // 1) old icon (cart 3, earlier round) → picker
  const ctx = await browser.newContext(iphone);
  const p = await ctx.newPage(); p.setDefaultTimeout(5000);
  p.on('pageerror', e => { console.log('PAGE ERROR', e.message); fails++; });
  await route(p); await p.addInitScript(d => { window.__docsInit = d; }, docs);
  await p.goto('http://app.test/?cart=3&r=111'); await p.waitForTimeout(800);
  ok(await p.isVisible('#step-cartpick'), 'old Cart 3 icon in a 2-cart round asks which cart');
  const carts = await p.$$eval('.cartpick', e => e.map(x => x.textContent.replace(/\s+/g, ' ').trim()));
  ok(carts.length === 2 && carts[0].includes('Brent, Mike') && carts[1].includes('John, Chad'), 'lists today\'s carts with names: ' + carts.join(' | '));
  await p.screenshot({ path: __dirname + '/shots/cartpick.png' });
  await p.click('.cartpick:has-text("John")'); await p.waitForTimeout(400);
  ok(await p.isVisible('#step-3') && await p.evaluate(() => lockedTeamId === 2) && (await p.textContent('#entry-container')).includes('John'), 'picked Cart 2: scoring John & Chad');
  ok(!(await p.isVisible('#hs-modal')), 'no Home Screen question in the icon');
  await p.reload(); await p.waitForTimeout(800);
  ok(await p.isVisible('#step-3') && await p.evaluate(() => lockedTeamId === 2), 'remembers the pick for this round');
  // old link with no round at all (sent before this update)
  const p0 = await ctx.newPage(); await route(p0); await p0.addInitScript(d => { window.__docsInit = d; }, docs);
  await p0.evaluate(() => localStorage.clear()).catch(() => {});
  // 2) today's link in Safari on an iPhone → straight to the cart + Home Screen question
  const ctx2 = await browser.newContext(iphone);
  const s = await ctx2.newPage(); s.setDefaultTimeout(5000);
  s.on('pageerror', e => { console.log('PAGE ERROR', e.message); fails++; });
  await route(s); await s.addInitScript(d => { window.__docsInit = d; }, docs);
  await s.goto(`http://app.test/?cart=2&r=${rid}`); await s.waitForTimeout(1500);
  ok(await s.isVisible('#step-3') && await s.evaluate(() => lockedTeamId === 2), "today's link goes straight to Cart 2");
  ok(await s.isVisible('#hs-modal') && (await s.textContent('#hs-ask')).includes('Do you have the JB Golf app on your Home Screen?'), 'asks about the Home Screen app');
  await s.screenshot({ path: __dirname + '/shots/hs-ask.png' });
  await s.click('#hs-ask button:has-text("Yes")');
  ok((await s.textContent('#hs-yes')).includes('Tap Cart 2'), 'Yes: open the icon and tap Cart 2');
  await s.screenshot({ path: __dirname + '/shots/hs-yes.png' });
  await s.click('#hs-yes .btn-secondary');
  await s.reload(); await s.waitForTimeout(1500);
  ok(!(await s.isVisible('#hs-modal')), 'asked only once per round');
  await s.evaluate(() => { localStorage.removeItem('jbHsAsked_' + roundData.roundId); maybeAskHomeScreen(); answerHomeScreen(false); });
  ok((await s.textContent('#hs-no')).includes('Add to Home Screen') && (await s.textContent('#hs-no')).includes('Cart 2'), 'No: how to add it');
  await s.screenshot({ path: __dirname + '/shots/hs-no.png' });
  await browser.close();
  console.log(fails ? `${fails} FAILED` : 'ALL PASS'); process.exit(fails ? 1 : 0);
})();
