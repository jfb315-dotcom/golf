const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const fs = require('fs');
const stub = fs.readFileSync(__dirname + '/stub.js', 'utf8');
const html = fs.readFileSync(__dirname + '/../index.html', 'utf8');
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const page = await browser.newPage({ viewport: { width: 390, height: 600 }, deviceScaleFactor: 2, hasTouch: true });
  page.setDefaultTimeout(5000);
  page.on('pageerror', e => { console.log('PAGE ERROR', e.message); fails++; });
  await page.route('**/*', r => { const u = r.request().url();
    if (u.includes('gstatic')) return r.fulfill({ contentType: 'text/javascript', body: u.includes('app-compat') ? stub : '' });
    if (u.startsWith('http://app.test/')) return r.fulfill({ contentType: 'text/html', body: html });
    return r.abort(); });
  await page.goto('http://app.test/'); await page.waitForTimeout(500);
  await page.evaluate(() => window.scrollTo(0, 200)); await page.waitForTimeout(100);
  const y0 = await page.evaluate(() => window.scrollY); console.log('h0', await page.evaluate(() => [document.documentElement.scrollHeight, innerHeight]));
  await page.evaluate(() => openSignupModal()); await page.waitForTimeout(200);
  await page.mouse.move(195, 300); await page.mouse.wheel(0, 600); await page.waitForTimeout(200);
  await page.mouse.wheel(0, -600); await page.waitForTimeout(200);
  const top = await page.evaluate(() => document.querySelector('#step-home').getBoundingClientRect().top);
  ok(await page.evaluate(() => document.body.classList.contains('modal-open')), 'page behind is locked while the popup is open');
  await page.mouse.wheel(0, 400); await page.waitForTimeout(200);
  ok(await page.evaluate(() => document.querySelector('#step-home').getBoundingClientRect().top) === top, 'page behind does not move when scrolling on the popup');
  await page.click('#signup-modal .btn-secondary'); await page.waitForTimeout(200);
  const y1 = await page.evaluate(() => window.scrollY); console.log('y1', y1, await page.evaluate(() => [document.documentElement.scrollHeight, innerHeight])); ok(y1 === y0 && !(await page.evaluate(() => document.body.classList.contains('modal-open'))), `closing puts the page back where it was (${y0})`);
  await browser.close();
  console.log(fails ? `${fails} FAILED` : 'ALL PASS'); process.exit(fails ? 1 : 0);
})();
