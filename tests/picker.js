const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const fs = require('fs');
const stub = fs.readFileSync(__dirname + '/stub.js', 'utf8');
const html = fs.readFileSync(__dirname + '/../index.html', 'utf8');
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  page.setDefaultTimeout(5000);
  page.on('pageerror', e => { console.log('PAGE ERROR', e.message); fails++; });
  const msgs = []; page.on('dialog', d => { msgs.push(d.message()); d.accept(); });
  await page.route('**/*', r => { const u = r.request().url();
    if (u.includes('gstatic')) return r.fulfill({ contentType: 'text/javascript', body: u.includes('app-compat') ? stub : '' });
    if (u.startsWith('http://app.test/')) return r.fulfill({ contentType: 'text/html', body: html });
    return r.abort(); });
  await page.addInitScript(() => {
    const players = {};
    [['Brent','Smith','Blue','4, 12'],['Mike','Davis','White',''],['Jordan','Lee','Gold',''],['Joe','Brown','White',''],['Sam','Hill','Blue',''],['Tom','King','White','']].forEach(([f,l,t,st]) => players[(f+' '+l).toLowerCase()] = { name: f+' '+l, first: f, last: l, tee: t, strokes: { cleveland_cc: st } });
    window.__docsInit = { saved_players: { players } };
  });
  await page.goto('http://app.test/'); await page.waitForTimeout(500); await page.evaluate(() => { if (document.getElementById('step-home')?.classList.contains('active')) showScreen('step-1'); });
  await page.selectOption('#course-selector', 'cleveland_cc');
  await page.evaluate(() => { document.getElementById('group-count').value = 2; document.getElementById('players-per-group').value = 2; });
  await page.click('#step-1 .bar-primary[onclick="goToStep2()"]');
  await page.click('.roster-team:nth-of-type(1) .roster-add-saved'); await page.waitForTimeout(150);
  ok(await page.isVisible('#roster-picker') && (await page.textContent('#rp-title')) === 'Team 1', 'picker opens for Team 1');
  ok((await page.$$('.rp-row')).length === 6, '6 saved players listed');
  await page.click('.rp-row:has-text("Mike Davis")'); await page.click('.rp-row:has-text("Brent Smith")');
  ok(await page.inputValue('#g1-p1-name') === 'Mike Davis' && await page.inputValue('#g1-p2-name') === 'Brent Smith', 'picked in order: Mike captain, Brent 2nd');
  ok(await page.inputValue('#g1-p2-tee') === 'Blue' && await page.inputValue('#g1-p2-strokes') === '4, 12', 'Brent gets his tee and strokes');
  ok((await page.textContent('.rp-row.on:has-text("Brent") .rp-num')) === '2', 'order number shown');
  await page.screenshot({ path: __dirname + '/shots/picker.png' });
  await page.click('.rp-row:has-text("Jordan")');
  ok(msgs.some(m => m.includes('Team 1 is full')), 'full team warns');
  await page.click('.rp-row:has-text("Mike Davis")');
  ok(await page.inputValue('#g1-p1-name') === '' , 'tap again removes Mike');
  await page.click('.rp-row:has-text("Jordan")');
  ok(await page.inputValue('#g1-p1-name') === 'Jordan Lee', 'Jordan fills the open spot');
  await page.click('#roster-picker .btn-primary');
  await page.click('.roster-team:nth-of-type(2) .roster-add-saved'); await page.waitForTimeout(100);
  ok(await page.isDisabled('.rp-row:has-text("Brent")') && (await page.textContent('.rp-row:has-text("Brent") .rp-note')) === 'Team 1', 'Team 2 picker shows Brent taken by Team 1');
  await page.fill('#rp-search', 'sam'); 
  ok((await page.$$('.rp-row')).length === 1, 'search filters');
  await page.click('.rp-row:has-text("Sam")'); await page.click('#roster-picker .btn-primary');
  ok(await page.inputValue('#g2-p1-name') === 'Sam Hill' && await page.evaluate(() => tempRosterCache['g2-p1-name']) === 'Sam Hill', 'Sam on Team 2 and cached');
  await browser.close();
  console.log(fails ? `${fails} FAILED` : 'ALL PASS'); process.exit(fails ? 1 : 0);
})();
